"""Synthetic decoy generation: PDF, DOCX, XLSX, CSV, TXT and ZIP.

Everything is generated content - names, financial figures and
"credential-like" strings are plausible-looking but wholly synthetic, never
copied from real data, and never usable on a real system.

Optional libraries (reportlab / python-docx / openpyxl) are used when
installed; otherwise compact stdlib fallback writers produce valid minimal
files so the lab works offline. Fallback output is verified by tests.
"""

from __future__ import annotations

import csv
import io
import random
import zipfile
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from honeytrace.deception.tokens import TokenRegistry

COMPANIES = [
    "Acme Logistics", "Nordwind Trading", "BlueRiver Analytics",
    "Cobalt & Sons", "Meridian Health Group", "Vantage Freight",
]
FIRST = ["Ava", "Noah", "Mia", "Liam", "Zoe", "Ethan", "Nora", "Owen"]
LAST = ["Taylor", "Bakker", "Okafor", "Silva", "Novak", "Fischer", "Marsh", "Ito"]
DOMAINS = ["example-lab.invalid", "corp-lab.test", "acme-lab.internal"]


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class DecoyContent:
    """A generated decoy awaiting placement."""

    def __init__(self, path: Path, decoy_type: str, profile: str, payload: bytes):
        self.path = path
        self.decoy_type = decoy_type
        self.profile = profile
        self.payload = payload

    def write(self) -> Path:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_bytes(self.payload)
        return self.path


def _person(rng: random.Random) -> str:
    return f"{rng.choice(FIRST)} {rng.choice(LAST)}"


def _money(rng: random.Random, low: float, high: float) -> float:
    return round(rng.uniform(low, high), 2)


def _creds(rng: random.Random) -> List[str]:
    """Synthetic credential-shaped strings. Obvious fakes, safe by design."""
    lines = []
    for _ in range(rng.randint(4, 8)):
        user = f"{rng.choice(FIRST).lower()}.{rng.choice(LAST).lower()}"
        pwd = f"Sample-NotReal-{rng.randint(1000, 9999)}!a"
        lines.append(f"{user}@{rng.choice(DOMAINS)}:{pwd}")
    return lines


class DecoyGenerator:
    def __init__(self, registry: TokenRegistry, seed: Optional[int] = None):
        self.registry = registry
        self.rng = random.Random(seed)  # deterministic when seeded

    # ------------------------------------------------------------------ #
    # Public API
    # ------------------------------------------------------------------ #

    def generate(
        self,
        directory: Path,
        decoy_type: str,
        name_pattern: str,
        content_profile: str,
        instance: int = 1,
        decoy_id: str = "unassigned",
    ) -> DecoyContent:
        """Generate one decoy file (not yet written to disk)."""
        filename = name_pattern.format(n=instance)
        token_url = self.registry.url_for(decoy_id)
        directory = Path(directory)

        if decoy_type == "pdf":
            payload = self._pdf(filename, content_profile, token_url)
        elif decoy_type == "docx":
            payload = self._docx(filename, content_profile, token_url)
        elif decoy_type == "xlsx":
            payload = self._xlsx(content_profile, token_url, decoy_id)
        elif decoy_type == "csv":
            payload = self._csv(content_profile).encode("utf-8")
        elif decoy_type == "zip":
            payload = self._zip(filename, content_profile, token_url)
        else:  # txt
            payload = self._txt(filename, content_profile, token_url).encode("utf-8")
        return DecoyContent(directory / filename, decoy_type, content_profile, payload)

    # ------------------------------------------------------------------ #
    # TXT / CSV
    # ------------------------------------------------------------------ #

    def _txt(self, filename: str, profile: str, token_url: str) -> str:
        rng = self.rng
        lines = [
            f"# {filename}",
            f"# Internal notes - {rng.choice(COMPANIES)} (LAB COPY - SYNTHETIC DATA)",
            f"# Generated by HoneyTrace decoy service at {_utcnow().isoformat()}",
            "",
        ]
        if profile == "credentials":
            lines.append("Recovered credentials (UNVERIFIED - DO NOT USE):")
            lines.extend(_creds(rng))
        elif profile == "notes":
            for i in range(rng.randint(5, 10)):
                lines.append(f"{i + 1}. {_person(rng)} to rotate VPN certs before 2026-{rng.randint(1, 12):02d}.")
        else:
            lines.append("Meeting notes: Q4 planning. Owner: " + _person(rng))
        lines += ["", f"[beacon] {token_url}", "[notice] Synthetic decoy content. Any access is logged."]
        return "\n".join(lines)

    def _csv(self, profile: str) -> str:
        rng = self.rng
        buf = io.StringIO()
        w = csv.writer(buf)
        if profile == "salary":
            w.writerow(["employee_id", "name", "role", "annual_salary_eur", "review_status"])
            for i in range(rng.randint(8, 14)):
                w.writerow([
                    f"EMP-{rng.randint(10000, 99999)}",
                    _person(rng),
                    rng.choice(["Engineer", "Analyst", "Manager", "Director"]),
                    _money(rng, 45000, 140000),
                    rng.choice(["pending", "approved", "draft"]),
                ])
        else:
            w.writerow(["date", "vendor", "amount_eur", "status"])
            for _ in range(rng.randint(8, 14)):
                w.writerow([
                    (_utcnow() - timedelta(days=rng.randint(1, 90))).date().isoformat(),
                    rng.choice(COMPANIES),
                    _money(rng, 120, 24000),
                    rng.choice(["paid", "open", "overdue"]),
                ])
        return buf.getvalue()

    # ------------------------------------------------------------------ #
    # PDF (reportlab if present, else minimal stdlib PDF)
    # ------------------------------------------------------------------ #

    def _pdf(self, filename: str, profile: str, token_url: str) -> bytes:
        try:
            from reportlab.lib.pagesizes import A4
            from reportlab.pdfgen import canvas

            buf = io.BytesIO()
            c = canvas.Canvas(buf, pagesize=A4)
            c.setFont("Helvetica-Bold", 16)
            c.drawString(72, 780, filename)
            c.setFont("Helvetica", 10)
            y = 750
            for line in self._pdf_lines(profile, token_url):
                c.drawString(72, y, line)
                y -= 14
            c.save()
            return buf.getvalue()
        except ImportError:
            return self._pdf_minimal(filename, profile, token_url)

    def _pdf_lines(self, profile: str, token_url: str) -> List[str]:
        rng = self.rng
        lines = ["HoneyTrace LAB DECOY - synthetic document, no real data"]
        if profile == "invoice":
            company = rng.choice(COMPANIES)
            lines.append(f"Invoice from: {company}")
            lines.append(f"Invoice no: INV-{rng.randint(100000, 999999)}")
            lines.append(f"Amount due: EUR {_money(rng, 500, 48000):,.2f}")
            lines.append(f"Contact: {_person(rng)} <billing@{rng.choice(DOMAINS)}>")
        else:
            lines.append(f"Subject: internal summary ({profile})")
            lines.append(f"Prepared by: {_person(rng)}")
        lines.append("")
        lines.append(f"Beacon: {token_url}")
        lines.append("Any fetch of the beacon URL is logged by the lab.")
        return lines

    def _pdf_minimal(self, filename: str, profile: str, token_url: str) -> bytes:
        """A valid single-page PDF using only the standard library."""
        lines = [l.replace("(", "[").replace(")", "]") for l in self._pdf_lines(profile, token_url)]
        text_ops = "BT /F1 10 Tf 50 780 Td 14 TL\n" + "\n".join(f"({l}) Tj T*" for l in lines) + "\nET"
        stream = text_ops.encode("latin-1", "replace")
        objects: List[bytes] = [
            b"<< /Type /Catalog /Pages 2 0 R >>",
            b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
            b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
            b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
        ]
        out = io.BytesIO()
        out.write(b"%PDF-1.4\n")
        offsets = [0]
        for i, obj in enumerate(objects, start=1):
            offsets.append(out.tell())
            out.write(f"{i} 0 obj\n".encode() + obj + b"\nendobj\n")
        xref_pos = out.tell()
        out.write(f"xref\n0 {len(objects) + 1}\n".encode())
        out.write(b"0000000000 65535 f \n")
        for off in offsets[1:]:
            out.write(f"{off:010d} 00000 n \n".encode())
        out.write(
            f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
            f"startxref\n{xref_pos}\n%%EOF\n".encode()
        )
        return out.getvalue()

    # ------------------------------------------------------------------ #
    # DOCX (python-docx if present, else minimal OOXML)
    # ------------------------------------------------------------------ #

    def _docx(self, filename: str, profile: str, token_url: str) -> bytes:
        try:
            import docx

            doc = docx.Document()
            doc.add_heading(filename, level=1)
            for line in self._docx_lines(profile, token_url):
                doc.add_paragraph(line)
            buf = io.BytesIO()
            doc.save(buf)
            return buf.getvalue()
        except ImportError:
            return self._docx_minimal(filename, profile, token_url)

    def _docx_lines(self, profile: str, token_url: str) -> List[str]:
        lines = ["HoneyTrace LAB DECOY - synthetic document, no real data."]
        if profile == "notes":
            lines.append(f"Server notes compiled by {_person(rng := self.rng)}")
            lines.append(f"Ticket: OPS-{rng.randint(1000, 9999)} - rotate SSH host keys on lab-vm-{rng.randint(1, 9)}")
        else:
            lines.append(f"Author: {_person(self.rng)}")
        lines.append(f"Beacon: {token_url}")
        return lines

    def _docx_minimal(self, filename: str, profile: str, token_url: str) -> bytes:
        paragraphs = "".join(
            f"<w:p><w:r><w:t xml:space=\"preserve\">{p}</w:t></w:r></w:p>"
            for p in [
                filename,
                *self._docx_lines(profile, token_url),
            ]
        )
        document = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
            f"<w:body>{paragraphs}</w:body></w:document>"
        )
        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/word/document.xml" ContentType='
            '"application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
            "</Types>"
        )
        rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type='
            '"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
            'Target="word/document.xml"/></Relationships>'
        )
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("[Content_Types].xml", content_types)
            zf.writestr("_rels/.rels", rels)
            zf.writestr("word/document.xml", document)
        return buf.getvalue()

    # ------------------------------------------------------------------ #
    # XLSX (openpyxl if present, else minimal OOXML)
    # ------------------------------------------------------------------ #

    def _xlsx(self, profile: str, token_url: str, decoy_id: str) -> bytes:
        try:
            from openpyxl import Workbook

            wb = Workbook()
            ws = wb.active
            ws.title = "Q4"
            rows = self._xlsx_rows(profile)
            for row in rows:
                ws.append(row)
            ws.append([])
            ws.append(["beacon", token_url])
            buf = io.BytesIO()
            wb.save(buf)
            return buf.getvalue()
        except ImportError:
            return self._xlsx_minimal(profile, token_url)

    def _xlsx_rows(self, profile: str) -> List[List[Any]]:
        rng = self.rng
        rows: List[List[Any]] = [["HoneyTrace LAB DECOY - synthetic data"], []]
        if profile == "budget":
            rows.append(["cost_center", "owner", "q3_actual", "q4_forecast"])
            for _ in range(rng.randint(6, 12)):
                rows.append([
                    f"CC-{rng.randint(100, 999)}",
                    _person(rng),
                    _money(rng, 10000, 500000),
                    _money(rng, 10000, 600000),
                ])
        else:
            rows.append(["item", "value"])
            rows.append(["prepared_by", _person(rng)])
        return rows

    def _xlsx_minimal(self, profile: str, token_url: str) -> bytes:
        rows = self._xlsx_rows(profile) + [[], ["beacon", token_url]]

        def cell(v: Any, ref: str) -> str:
            if isinstance(v, (int, float)):
                return f'<c r="{ref}"><v>{v}</v></c>'
            v = str(v).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            return f'<c r="{ref}" t="inlineStr"><is><t>{v}</t></is></c>'

        sheet_rows = []
        for r, row in enumerate(rows, start=1):
            cells = "".join(cell(v, f"{chr(65 + c)}{r}") for c, v in enumerate(row[:8]))
            sheet_rows.append(f'<row r="{r}">{cells}</row>')
        sheet = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
            f"<sheetData>{''.join(sheet_rows)}</sheetData></worksheet>"
        )
        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/xl/workbook.xml" ContentType='
            '"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
            '<Override PartName="/xl/worksheets/sheet1.xml" ContentType='
            '"application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
            "</Types>"
        )
        rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type='
            '"http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
            'Target="xl/workbook.xml"/></Relationships>'
        )
        workbook = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
            'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
            '<sheets><sheet name="Q4" sheetId="1" r:id="rId1"/></sheets></workbook>'
        )
        wb_rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type='
            '"http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" '
            'Target="worksheets/sheet1.xml"/></Relationships>'
        )
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("[Content_Types].xml", content_types)
            zf.writestr("_rels/.rels", rels)
            zf.writestr("xl/workbook.xml", workbook)
            zf.writestr("xl/_rels/workbook.xml.rels", wb_rels)
            zf.writestr("xl/worksheets/sheet1.xml", sheet)
        return buf.getvalue()

    # ------------------------------------------------------------------ #
    # ZIP
    # ------------------------------------------------------------------ #

    def _zip(self, filename: str, profile: str, token_url: str) -> bytes:
        rng = self.rng
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("README.txt", self._txt("README.txt", profile, token_url))
            zf.writestr("data/export.csv", self._csv(profile))
            for i in range(rng.randint(2, 4)):
                zf.writestr(f"logs/app-{i}.log", self._txt(f"app-{i}.log", "notes", token_url))
        return buf.getvalue()
